<?php
// Длинный заголовок сокращает бренд в конце до «| Платформа»; короткий и чужой хвост не трогаем.
pn_t('seo_title: длинный заголовок — бренд короче', function () {
    $long = 'Ипотека на квартиру в Екатеринбурге от 6 % — калькулятор и подбор программы | Платформа недвижимости';
    pn_eq(seo_title($long), 'Ипотека на квартиру в Екатеринбурге от 6 % — калькулятор и подбор программы | Платформа');
});
pn_t('seo_title: короткий заголовок не меняется', function () {
    pn_eq(seo_title('Ремонт квартир | Платформа недвижимости'), 'Ремонт квартир | Платформа недвижимости');
    pn_eq(seo_title(str_repeat('а', 80)), str_repeat('а', 80));
});
pn_t('seo_meta: в <title> и og:title — сокращённый заголовок', function () {
    $h = seo_meta(['title' => str_repeat('Квартира ', 8) . '| Платформа недвижимости', 'description' => 'x', 'path' => ''], []);
    pn_ok(str_contains($h, '| Платформа</title>'), 'title');
    pn_ok(str_contains($h, 'og:title" content="' . str_repeat('Квартира ', 8) . '| Платформа"'), 'og');
});
